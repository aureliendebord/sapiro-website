// Helper pour créer un animal
function createAnimal(
  id: string,
  name: string,
  animalClass: AnimalClass,
  order: string,
  family: string,
  scientificName: string,
  conservationStatus: string,
  imageSource: string = "",
  imageLicense: string = "CC-BY-SA 4.0",
): Animal {
  return {
    id,
    name,
    type: "animal",
    flagPath: "",
    tags: [animalClass, family],
    animalClass,
    order,
    family,
    scientificName,
    conservationStatus,
    imageUrl: getAnimalUrl(animalClass, id),
    imageSource,
    imageLicense,
  };
}

