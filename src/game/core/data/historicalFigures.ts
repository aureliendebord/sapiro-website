// Helper pour créer un personnage
function createFigure(
  id: string,
  name: string,
  fullName: string,
  birthYear: number,
  deathYear: number | null,
  gender: FigureGender,
  birthCountry: string,
  birthCity: string,
  nationality: string,
  continent: FigureContinent,
  category: FigureCategory,
  era: FigureEra,
  professions: string[],
  knownFor: string,
  imageSource: string = "",
  imageLicense: string = "Public Domain",
): HistoricalFigure {
  // Exclure automatiquement des quiz de nationalité si la nationalité
  // correspond à une entité politique disparue (Empire romain, URSS,
  // Yougoslavie, etc.). On passe par le mapping FR → code pour rester
  // robuste pendant la migration progressive vers les codes (Phase 4).
  // Tant que les données ne sont pas migrées, `nationality` est encore
  // en FR — on résout vers code via FR_NAME_TO_NATIONALITY_CODE.
  const nationalityCode = FR_NAME_TO_NATIONALITY_CODE[nationality];
  const excludeFromNationalityQuiz = nationalityCode
    ? HISTORICAL_NATIONALITY_CODES.has(nationalityCode)
    : false;

  if (__DEV__ && !nationalityCode) {
    // Signaler les nationalités sans mapping pour qu'on les ajoute dans
    // `data/codes/nationalities.ts` — préserve l'intégrité du quiz.
    console.warn(
      `[historicalFigures] Nationalité sans code mapping : "${nationality}" ` +
        `(personnage id=${id}). Ajouter dans data/codes/nationalities.ts.`,
    );
  }

  return {
    id,
    name,
    type: "figure",
    flagPath: "", // Non utilisé pour les figures
    tags: [category, era, continent],
    fullName,
    birthYear,
    deathYear,
    gender,
    birthCountry,
    birthCity,
    nationality,
    continent,
    category,
    era,
    professions,
    knownFor,
    portraitUrl: getPortraitUrl(category, id),
    imageSource,
    imageLicense,
    ...(excludeFromNationalityQuiz && { excludeFromNationalityQuiz }),
  };
}

