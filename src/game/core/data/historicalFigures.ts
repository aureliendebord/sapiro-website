/**
 * Obtenir des personnages par catégorie
 */
export function getFiguresByCategory(category: FigureCategory): HistoricalFigure[] {
  return historicalFigures.filter((f) => f.category === category);
}

/**
 * Obtenir des personnages par époque
 */
export function getFiguresByEra(era: FigureEra): HistoricalFigure[] {
  return historicalFigures.filter((f) => f.era === era);
}

/**
 * Obtenir des personnages par continent
 */
export function getFiguresByContinent(continent: FigureContinent): HistoricalFigure[] {
  return historicalFigures.filter((f) => f.continent === continent);
}

/**
 * Obtenir des personnages par nationalité
 */
export function getFiguresByNationality(nationality: string): HistoricalFigure[] {
  return historicalFigures.filter((f) =>
    f.nationality.toLowerCase().includes(nationality.toLowerCase()),
  );
}

/**
 * Obtenir des personnages aléatoires
 */
export function getRandomFigures(count: number, exclude: string[] = []): HistoricalFigure[] {
  const available = historicalFigures.filter((f) => !exclude.includes(f.id));
  return shuffleArray(available).slice(0, count);
}

/**
 * Obtenir un personnage par ID
 */
export function getFigureById(id: string): HistoricalFigure | undefined {
  return historicalFigures.find((f) => f.id === id);
}

/**
 * Obtenir les pays de naissance uniques
 */
export function getUniqueBirthCountries(): string[] {
  const countries = new Set(historicalFigures.map((f) => f.birthCountry));
  return Array.from(countries).sort();
}

/**
 * Obtenir les villes de naissance uniques
 */
export function getUniqueBirthCities(): string[] {
  const cities = new Set(historicalFigures.map((f) => f.birthCity));
  return Array.from(cities).sort();
}

/**
 * Obtenir les professions uniques
 */
export function getUniqueProfessions(): string[] {
  const professions = new Set(historicalFigures.flatMap((f) => f.professions));
  return Array.from(professions).sort();
}

/**
 * Rechercher des personnages
 */
export function searchFigures(query: string): HistoricalFigure[] {
  const lowerQuery = query.toLowerCase();
  return historicalFigures.filter(
    (f) =>
      f.name.toLowerCase().includes(lowerQuery) ||
      f.fullName.toLowerCase().includes(lowerQuery) ||
      f.nationality.toLowerCase().includes(lowerQuery) ||
      f.birthCountry.toLowerCase().includes(lowerQuery) ||
      f.birthCity.toLowerCase().includes(lowerQuery) ||
      f.knownFor.toLowerCase().includes(lowerQuery) ||
      f.professions.some((p) => p.toLowerCase().includes(lowerQuery)),
  );
}
