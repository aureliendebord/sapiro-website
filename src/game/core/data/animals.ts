// Fonctions de filtrage
export function getAnimalsByClass(animalClass: AnimalClass): Animal[] {
  return allAnimals.filter((a) => a.animalClass === animalClass);
}

export function getAnimalsByFamily(family: string): Animal[] {
  return allAnimals.filter((a) => a.family === family);
}

export function getAnimalsByFamilies(families: string[]): Animal[] {
  return allAnimals.filter((a) => families.includes(a.family));
}

export function getAnimalsByConservationStatus(status: string): Animal[] {
  return allAnimals.filter((a) => a.conservationStatus === status);
}

export function getAnimalsByOrder(order: string): Animal[] {
  return allAnimals.filter((a) => a.order === order);
}

export function getAnimalById(id: string): Animal | undefined {
  return allAnimals.find((a) => a.id === id);
}

export function searchAnimals(query: string): Animal[] {
  const lowerQuery = query.toLowerCase();
  return allAnimals.filter(
    (a) =>
      a.name.toLowerCase().includes(lowerQuery) ||
      a.scientificName.toLowerCase().includes(lowerQuery) ||
      a.family.toLowerCase().includes(lowerQuery) ||
      a.order.toLowerCase().includes(lowerQuery),
  );
}

export function getUniqueOrders(): string[] {
  const orders = new Set(allAnimals.map((a) => a.order));
  return Array.from(orders).sort();
}

export function getUniqueFamilies(): string[] {
  const families = new Set(allAnimals.map((a) => a.family));
  return Array.from(families).sort();
}
