// Helper functions
export function getRegionsByOverseas(isOverseas: boolean): FrenchRegion[] {
  return frenchRegions.filter((r) => r.isOverseas === isOverseas);
}

export function getRegionsByTag(tag: string): FrenchRegion[] {
  return frenchRegions.filter((r) => r.tags.includes(tag));
}

export function getRandomRegions(count: number, exclude?: string[]): FrenchRegion[] {
  const available = exclude ? frenchRegions.filter((r) => !exclude.includes(r.id)) : frenchRegions;

  const shuffled = shuffleArray(available);
  return shuffled.slice(0, count);
}
