// Helper functions
export function getOrgsByCategory(
  category: "political" | "economic" | "sports" | "humanitarian",
): InternationalOrg[] {
  return internationalOrgs.filter((o) => o.category === category);
}

export function getOrgsByTag(tag: string): InternationalOrg[] {
  return internationalOrgs.filter((o) => o.tags.includes(tag));
}

export function getRandomOrgs(count: number, exclude?: string[]): InternationalOrg[] {
  const available = exclude
    ? internationalOrgs.filter((o) => !exclude.includes(o.id))
    : internationalOrgs;

  const shuffled = shuffleArray(available);
  return shuffled.slice(0, count);
}
