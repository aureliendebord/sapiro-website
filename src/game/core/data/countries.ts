// Helper functions
export function getCountriesByContinent(continent: string): Country[] {
  return countries.filter((c) => c.continent === continent);
}

export function getCountriesByTag(tag: string): Country[] {
  return countries.filter((c) => c.tags.includes(tag));
}

export function getCountriesByPopulation(min: number, max?: number): Country[] {
  return countries.filter((c) => {
    if (max) {
      return c.population >= min && c.population <= max;
    }
    return c.population >= min;
  });
}

export function getRandomCountries(count: number, exclude?: string[]): Country[] {
  const available = exclude ? countries.filter((c) => !exclude.includes(c.code)) : countries;

  const shuffled = shuffleArray(available);
  return shuffled.slice(0, count);
}

export function getCountryByCode(code: string): Country | undefined {
  return countries.find((c) => c.code === code);
}
