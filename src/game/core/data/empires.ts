// Helper functions
export function getEmpiresByEra(era: "ancient" | "medieval" | "modern"): HistoricalEmpire[] {
  return historicalEmpires.filter((e) => e.era === era);
}

export function getEmpiresByTag(tag: string): HistoricalEmpire[] {
  return historicalEmpires.filter((e) => e.tags.includes(tag));
}

export function getRandomEmpires(count: number, exclude?: string[]): HistoricalEmpire[] {
  const available = exclude
    ? historicalEmpires.filter((e) => !exclude.includes(e.id))
    : historicalEmpires;

  const shuffled = shuffleArray(available);
  return shuffled.slice(0, count);
}
